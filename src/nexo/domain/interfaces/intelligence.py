from typing import Any, Protocol

from nexo.domain.models.intelligence import (
    ChatMessage,
    KnowledgeHit,
    Methodology,
    ToolCall,
)


class IntelligenceProvider(Protocol):
    def plan(
        self, context: str, declarations: list[dict[str, Any]]
    ) -> tuple[ToolCall, ...]: ...
    def synthesize(self, context: str) -> str: ...
    def extract(self, content: str, *, video: bool = False) -> Methodology: ...
    def test_connection(self) -> str: ...
    def close(self) -> None: ...


class KnowledgeRetriever(Protocol):
    def search(self, query: str, limit: int = 4) -> tuple[KnowledgeHit, ...]: ...


class IntelligenceStorage(Protocol):
    def get_state(self, key: str) -> dict[str, Any]: ...
    def set_state(self, key: str, value: dict[str, Any]) -> None: ...
    def conversations(self) -> tuple[str, ...]: ...
    def clear_conversations(self) -> None: ...
    def history(
        self, conversation_id: str, limit: int = 12
    ) -> tuple[ChatMessage, ...]: ...
    def save_turn(self, conversation_id: str, question: str, answer: str) -> None: ...
    def methodologies(self) -> tuple[Methodology, ...]: ...
    def save_methodology(self, method: Methodology) -> None: ...
    def documents(self) -> list[dict[str, Any]]: ...
    def put_document(self, document: dict[str, Any]) -> None: ...
    def delete_document(self, identity: str) -> None: ...
